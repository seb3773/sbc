#!/usr/bin/env python3
"""Emit sbc_cipher_tables.h: the block-cipher constants sbc.exe keeps in .text.

All tables are stored in the binary as little-endian 32-bit words (the x86
image's own layout), so reading them with '<I' gives the algorithm's words.
Offsets are raw file offsets, found with `grep`-style scans of sbc.exe:

  0x58160  Twofish q0 (256 bytes) and q1 (256 bytes)
  0x59360  CAST-128 S1..S8 (8 x 256 words)
  0x5b360  Blowfish S0..S3 (4 x 256 words), then P (18 words) at 0x5c360

Run from the project root:  python3 tools/gen_cipher_tables.py
"""
import struct
import sys

EXE = "sbc.exe"
OUT = "sbc_cipher_tables.h"


def words(data, off, n):
    return struct.unpack("<%dI" % n, data[off:off + 4 * n])


def emit_u32(f, name, vals, per_line=6):
    f.write("static const uint32_t %s[%d] = {\n" % (name, len(vals)))
    for i in range(0, len(vals), per_line):
        f.write("    " + ", ".join("0x%08xu" % v for v in vals[i:i + per_line]) + ",\n")
    f.write("};\n\n")


def main():
    data = open(EXE, "rb").read()
    with open(OUT, "w") as f:
        f.write("/* Generated by tools/gen_cipher_tables.py from sbc.exe -- do not edit. */\n")
        f.write("#ifndef SBC_CIPHER_TABLES_H\n#define SBC_CIPHER_TABLES_H\n\n#include <stdint.h>\n\n")

        # Twofish: q0/q1 are byte permutations.
        f.write("static const uint8_t sbc_tf_q0[256] = {\n")
        for i in range(0, 256, 16):
            f.write("    " + ", ".join("0x%02x" % b for b in data[0x58160 + i:0x58160 + i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("static const uint8_t sbc_tf_q1[256] = {\n")
        for i in range(0, 256, 16):
            f.write("    " + ", ".join("0x%02x" % b for b in data[0x58260 + i:0x58260 + i + 16]) + ",\n")
        f.write("};\n\n")

        # CAST-128: 8 S-boxes of 256 32-bit words.
        cast = words(data, 0x59360, 8 * 256)
        for s in range(8):
            emit_u32(f, "sbc_cast_s%d" % (s + 1), cast[s * 256:(s + 1) * 256])

        # Blowfish: four S-boxes then the P array.
        bf_s = words(data, 0x5b360, 4 * 256)
        for s in range(4):
            emit_u32(f, "sbc_bf_s%d" % s, bf_s[s * 256:(s + 1) * 256])
        emit_u32(f, "sbc_bf_p", words(data, 0x5c360, 18))

        f.write("#endif /* SBC_CIPHER_TABLES_H */\n")
    print("wrote %s" % OUT)


if __name__ == "__main__":
    sys.exit(main())
